std::string FrancaGeneratorExtensions::generateCommonApiLicenseHeader()
{
    std::string header = R"(/*
* This file was generated by the BST IDL Generator.
* Compatible to org.genivi.commonapi.core CORE.
* Compatible to org.franca.core VERSION.
*/)";
    auto coreVersion = getCoreVersion();
    auto francaVersion = getFrancaVersion();
    header = header.replace(header.find("CORE"), 4, coreVersion);
    header = header.replace(header.find("VERSION"), 7, francaVersion);
    return header;
}

